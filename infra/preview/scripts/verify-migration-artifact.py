#!/usr/bin/env python3
"""Verify and reproduce a migration artifact from an exact Git commit.

This compares the complete artifact, including SQL, against an independent extraction of the
commit. It does not authorize the commit or PR: the caller must verify current GitHub state and
the source of its inputs immediately before privileged use. On success the regenerated bytes,
not the supplied file, are written to stdout. Failures write no artifact to stdout.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import stat
import subprocess
import sys

MAX_WIRE_BYTES = 32 * 1024 * 1024
spec = importlib.util.spec_from_file_location("migration_artifact", Path(__file__).with_name("migration-artifact.py"))
producer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(producer)


def read_artifact(path):
    # Reject symlinks and non-regular files before reading, including FIFOs that could block.
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, "rb") as source:
        info = os.fstat(source.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_WIRE_BYTES:
            raise ValueError("artifact is not a bounded regular file")
        data = source.read(MAX_WIRE_BYTES + 1)
    if len(data) > MAX_WIRE_BYTES:
        raise ValueError("artifact exceeds its wire limit")
    return data


def verify(repo, commit, path):
    supplied = read_artifact(path)
    expected = (json.dumps(producer.build(repo, commit), ensure_ascii=True, separators=(",", ":")) + "\n").encode("ascii")
    if len(expected) > MAX_WIRE_BYTES or supplied != expected:
        raise ValueError("artifact does not match the selected commit")
    return expected


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", required=True)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--artifact", required=True)
    args = parser.parse_args()
    try:
        verified = verify(args.repo, args.commit, args.artifact)
    except (OSError, UnicodeError, ValueError, subprocess.TimeoutExpired) as error:
        print(f"verify-migration-artifact: {error}", file=sys.stderr)
        return 1
    sys.stdout.buffer.write(verified)
    return 0


if __name__ == "__main__":
    sys.exit(main())
