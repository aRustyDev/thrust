"""Render the findings-file tables from out/*.json so the markdown numbers can be regenerated and diffed.

    uv run render_tables.py --out <dir> > <dir>/tables.md
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path


def md(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(x).replace("|", "\\|") for x in r) + " |")
    return "\n".join(out)


def render(o: Path):
    """Print the markdown tables for run output directory `o` to stdout."""
    L = lambda n: json.loads((o / n).read_text())  # noqa: E731
    run, ssum, rep, eff, cst = L("RUN.json"), L("server-summary.json"), L("join-report.json"), L("effort-summary.json"), L("client-scan-stats.json")
    inv = L("endpoint-inventory.json")
    print(f"<!-- generated by render_tables.py at tree commit {run['tree_commit']} -->\n")

    print("## T1 server routes per surface\n")
    rows = []
    for s in ("internal", "space", "auth", "v1", "instance", "web", "schema"):
        v = ssum[s]
        rows.append([s, v["route_entries"], v["endpoint_rows_method_x_path"], v["distinct_norm_paths"], json.dumps(v["by_method"], sort_keys=True)])
    print(md(["surface", "path() entries", "method x path rows", "distinct paths", "rows by method"], rows))

    print("\n## T2 raw `path(` lines vs reachable entries (reconciliation)\n")
    rows = [[d, v["raw_path_lines"], v["reachable_entries"], ", ".join(v["files_never_reached"]) or "-"] for d, v in ssum["_reconciliation"]["per_dir"].items()]
    print(md(["conf dir/file", "raw `path(` lines", "reachable entries", "files never reached from ROOT_URLCONF"], rows))

    print("\n## T3 disposition of server rows (method x path)\n")
    disp = rep["disposition_by_surface"]
    cols = ["P0", "P1", "P2", "drop", "admin-only", "not-used", "infra", "v1-out-of-scope"]
    rows = [[s] + [disp[s].get(c, 0) for c in cols] + [sum(disp[s].values())] for s in disp]
    print(md(["surface"] + cols + ["total"], rows))

    print("\n## T4 client scan\n")
    rows = [
        ["files scanned (ts/tsx, excl. node_modules/build/tests/stories)", cst["files_scanned"]],
        ["APIService subclasses", cst["service_classes"]],
        ["`this.get|post|put|patch|delete|request(` call sites (textual regex)", cst["this_verb_textual_occurrences"]],
        ["call sites extracted", cst["calls_extracted"]],
        ["by client", json.dumps(cst["calls_by_client"], sort_keys=True)],
        ["path resolution", json.dumps(cst["resolution"], sort_keys=True)],
        ["non-axios path references (form action / redirect / fetch / asset URL / literal)", cst["path_refs_non_axios"]],
        ["  by kind", json.dumps(cst["path_refs_by_kind"], sort_keys=True)],
        ["service methods with no reference elsewhere (call sites)", cst["calls_with_no_use_elsewhere"]],
        ["  evidence (strict / loose / none)", json.dumps(cst["method_use_evidence"], sort_keys=True)],
    ]
    print(md(["measure", "value"], rows))

    print("\n## T5 join\n")
    rows = [
        ["client call sites (axios-style + non-axios refs, Plane-API paths)", rep["client_call_sites_total"] - rep["client_call_sites_external_not_plane_api"]],
        ["  external (presigned upload URL, GitHub API)", rep["client_call_sites_external_not_plane_api"]],
        ["  matched to a server route + verb", rep["client_call_sites_matched"]],
        ["  unmatched", rep["client_call_sites_unmatched"]],
        ["    of which service method never referenced elsewhere (dead)", rep["client_call_sites_unmatched_dead_vs_live"]["dead_service_method(no reference elsewhere)"]],
        ["    of which referenced (live-looking)", rep["client_call_sites_unmatched_dead_vs_live"]["live"]],
        ["path alternatives (a site can have several, e.g. serviceType fan-out)", rep["client_alternatives_total"]],
        ["  matched", rep["client_alternatives_matched"]],
        ["  unmatched by category", json.dumps(rep["client_unmatched_by_category"], sort_keys=True)],
        ["matched calls whose client path has NO trailing slash", len(rep["client_matched_without_trailing_slash"])],
        ["server rows (internal+space+instance+auth) with no client use", sum(rep["not_used_by_surface"].values())],
        ["  by surface", json.dumps(rep["not_used_by_surface"], sort_keys=True)],
        ["  internal by method", json.dumps(rep["not_used_internal_by_method"], sort_keys=True)],
        ["  internal: never called vs called only by a dead service method", json.dumps(rep["not_used_internal_by_status"], sort_keys=True)],
        ["routes used by >= 2 named apps (strict evidence)", len(rep["multi_client_routes"])],
        ["routes called from the shared packages/services layer", len(rep["routes_called_from_shared_packages_services"])],
    ]
    print(md(["measure", "value"], rows))

    print("\n## T6 unmatched call sites that look live (route does not exist on this server)\n")
    rows = [[u["site"], u["call"], u["verb"], u["status"][0]] for u in rep["client_call_sites_unmatched_list"] if not u["dead"]]
    print(md(["site", "call", "verb", "join status"], rows))

    print("\n## T7 effort by class (person-days, compat adapter only; unit costs are [inferred])\n")
    for scope, v in eff["scopes"].items():
        print(f"\n**{scope}** - {v['rows']} rows / {v['paths']} paths; foundations {v['foundations_days']} pd; total {v['total_days_low']} / {v['total_days_likely']} / {v['total_days_high']} pd (low / likely / high)\n")
        rows = [[c, cv["rows"], json.dumps(cv["complexity"], sort_keys=True), cv["marginal_days_low"], cv["marginal_days_likely"], cv["marginal_days_high"]] for c, cv in v["by_class"].items() if cv["rows"]]
        print(md(["class", "rows", "S/M/L", "marginal pd low", "likely", "high"], rows))

    print("\n## T8 minimum P0 slice\n")
    # `trigger` in effort-summary.json is the citation hand-read at the fork base (kept so older runs stay byte-comparable). When the
    # tree has a different layout, layout-report.json carries where the trigger token really is in THIS tree: show that, so a table
    # pasted from a pinned run never cites a path that does not exist there.
    resolved = {}
    if (o / "layout-report.json").is_file():
        resolved = (L("layout-report.json").get("slice_triggers") or {}).get("resolved") or {}

    def trig(e):
        r = resolved.get(e["id"])
        return f"{r['file']}:{r['line']}" if r else e["trigger"]

    rows = [[e["id"], e["stage"], e["kind"], e["method"], e["path"], e["class"] + "/" + e["complexity"], e["days"], ",".join(e["features"]), trig(e)] for e in eff["p0_slice"]["entries"]]
    print(md(["id", "stage", "kind", "method", "server path", "class/size", "pd", "features", "triggered at"], rows))
    print("\nFoundations in the slice:\n")
    rows = [[k, v["fraction"], v["days"], v["why"]] for k, v in eff["p0_slice"]["foundations_used"].items()]
    print(md(["foundation", "fraction", "pd", "scope"], rows))
    print("\nExcluded foundations: " + ", ".join(eff["p0_slice"]["excluded_foundations"]))

    print("\n## T9 permission decorators on compat-surface handlers\n")
    rows = [[k, n] for k, n in eff["permission_decorator_combos"].items()]
    print(md(["decorator / class permission @ level", "handler rows"], rows))

    print("\n## T10 routes with feature tag by disposition (internal + space + instance + auth)\n")
    c: dict = {}
    for r in inv:
        if r["surface"] in ("internal", "space", "instance", "auth"):
            f = (r["features"] or ["?"])[0]
            c.setdefault(f, Counter())[r["disposition"]] += 1
    rows = [[f] + [c[f].get(d, 0) for d in ("P0", "P1", "P2", "admin-only", "not-used")] + [sum(c[f].values())] for f in sorted(c)]
    print(md(["primary feature", "P0", "P1", "P2", "admin-only", "not-used", "rows"], rows))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, type=Path)
    render(ap.parse_args().out)


if __name__ == "__main__":
    main()
